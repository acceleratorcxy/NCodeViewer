# -*- coding: utf-8 -*-
import io
p = "CHANGELOG.md"
t = io.open(p, encoding="utf-8").read()
old = r"### 打包" "\n" + r"- 重新打包 `dist\NCViewer.exe`（性能优化，约 10.7 MB），冒烟通过。"
new = old + "\n" + "\n".join([
    "### 修改",
    "- **程序统计 S/F 显示具体值**（如 `S: 5000 · 8000`、`F: 300 · 600 · 1800 · 3000 · 5000`），不再显示范围。",
    "- **统计随段模式变化**：勾选「仅显示勾选段」后，程序统计按勾选段并集重新计算（行程/S/F/G 均为段内数据）。",
    "- **段列表改为多选勾选**（`[x]/[ ]` 标记），「仅显示当前段」改为「**仅显示勾选段**」：过滤为勾选段并集（全选=全程序、全不选=不显示）；切段时全量渲染，**不再残留上一段刀路**。",
    "### 测试",
    "- 新增/更新 3 例（多段并集与统计随段、S/F 具体值、全选/全不选边界）；测试总数 **105**，py38 / py311 双环境全绿。",
    "### 打包",
    r"- 重新打包 `dist\NCViewer.exe`（统计具体值 + 多段勾选，约 10.7 MB），冒烟通过。",
])
assert old in t, "CHANGELOG 锚点未找到"
io.open(p, "w", encoding="utf-8", newline="\n").write(t.replace(old, new))
print("CHANGELOG done")

